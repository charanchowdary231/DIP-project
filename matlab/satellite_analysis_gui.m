        'String', 'Built-up Min Intensity: 150', ...
        'FontSize', 8, 'HorizontalAlignment', 'left', ...
        'BackgroundColor', [0.16, 0.18, 0.23], ...
        'ForegroundColor', [0.85, 0.85, 0.85], ...
        'Units', 'normalized', 'Position', [0.05, 0.38, 0.90, 0.022]);
    sldBuilt = uicontrol('Parent', pnlLeft, 'Style', 'slider', ...
        'Min', 110, 'Max', 220, 'Value', 150, ...
        'Units', 'normalized', 'Position', [0.05, 0.35, 0.90, 0.023], ...
        'Callback', @(s, e) set(lblBuilt, 'String', sprintf('Built-up Min Intensity: %d', round(get(s, 'Value')))));

    % 7. Action Buttons
    uicontrol('Parent', pnlLeft, 'Style', 'pushbutton', ...
        'String', '▶  Run Complete Pipeline', ...
        'FontSize', 11, 'FontWeight', 'bold', ...
        'BackgroundColor', [0.15, 0.65, 0.35], ...
        'ForegroundColor', [1 1 1], ...
        'Units', 'normalized', 'Position', [0.05, 0.25, 0.90, 0.055], ...
        'Callback', @onRunPipeline);

    uicontrol('Parent', pnlLeft, 'Style', 'pushbutton', ...
        'String', '💾  Export All Images & CSV', ...
        'FontSize', 10, 'FontWeight', 'bold', ...
        'BackgroundColor', [0.75, 0.35, 0.15], ...
        'ForegroundColor', [1 1 1], ...
        'Units', 'normalized', 'Position', [0.05, 0.18, 0.90, 0.045], ...
        'Callback', @onExportResults);

    % Metric Summary Box
    pnlMetrics = uipanel('Parent', pnlLeft, ...
        'Title', ' QUALITY METRICS (Sec. VI) ', ...
        'FontSize', 8, 'FontWeight', 'bold', ...
        'ForegroundColor', [0.95, 0.75, 0.2], ...
        'BackgroundColor', [0.12, 0.14, 0.18], ...
        'Position', [0.04, 0.015, 0.92, 0.15]);

    txtMetrics = uicontrol('Parent', pnlMetrics, 'Style', 'text', ...
        'String', sprintf('MSE:  ---\nRMSE: ---\nPSNR: ---\nSSIM: ---'), ...
        'FontSize', 8, 'FontName', 'Courier', ...
        'HorizontalAlignment', 'left', ...
        'BackgroundColor', [0.12, 0.14, 0.18], ...
        'ForegroundColor', [0.85, 0.95, 0.85], ...
        'Units', 'normalized', 'Position', [0.05, 0.05, 0.90, 0.88]);

    %% --------------------------------------------------------------------
    %% UI LAYOUT: Right Display Panel (Viewer & Multi-view)
    %% --------------------------------------------------------------------
    pnlRight = uipanel('Parent', hFig, ...
        'Title', ' SATELLITE IMAGE VISUALIZER ', ...
        'FontSize', 11, 'FontWeight', 'bold', ...
        'ForegroundColor', [0.9, 0.92, 0.95], ...
        'BackgroundColor', [0.14, 0.16, 0.20], ...
        'Position', [0.285, 0.02, 0.70, 0.96]);

    % Main Display Axes
    axMain = axes('Parent', pnlRight, ...
        'Position', [0.05, 0.06, 0.90, 0.88], ...
        'Color', [0.08, 0.09, 0.11]);
    axis(axMain, 'off');

    %% --------------------------------------------------------------------
    %% AUTO-LOAD DEFAULT SATELLITE IMAGE UPON STARTUP
    %% --------------------------------------------------------------------
    defaultImgPath = fullfile(pwd, 'satellite.jpg');
    if ~exist(defaultImgPath, 'file')
        defaultImgPath = fullfile(pwd, '..', 'data', 'satellite.jpg');
    end

    if exist(defaultImgPath, 'file')
        loadDataset(defaultImgPath);
    end

    %% --------------------------------------------------------------------
    %% CALLBACK FUNCTIONS
    %% --------------------------------------------------------------------
    function onLoadImage(~, ~)
        [filename, pathname] = uigetfile({'*.jpg;*.png;*.tif;*.bmp', 'Satellite Images (*.jpg, *.png, *.tif, *.bmp)'});
        if filename ~= 0
            selectedPath = fullfile(pathname, filename);
            loadDataset(selectedPath);
        end
    end

    function loadDataset(imgPath)
        try
            [state.Igray, state.Irgb] = preprocess_image(imgPath);
            state.imageLoaded = true;
            set(lblFile, 'String', sprintf('Loaded: %s', getFileName(imgPath)));

            % Check for clean reference
            refCandidate = fullfile(fileparts(imgPath), 'satellite_clean.png');
            if exist(refCandidate, 'file')
                state.cleanRef = imread(refCandidate);
                if size(state.cleanRef, 3) > 1, state.cleanRef = rgb2gray(state.cleanRef); end
            end

            % Run pipeline once with defaults
            executePipeline();
            updateDisplay();
        catch ME
            errordlg(sprintf('Failed to load image:\n%s', ME.message), 'Error');
        end
    end

    function onRunPipeline(~, ~)
        if ~state.imageLoaded
            warndlg('Please load an image first.', 'Notice');
            return;
        end
        executePipeline();
        updateDisplay();
    end

    function executePipeline()
        % 1. CLAHE
        clipVal = get(sldClip, 'Value');
        state.Ienh = contrast_enhancement(state.Igray, 'ClipLimit', clipVal);

        % 2. Median Filter
        winIdx = get(ddWindow, 'Value');
        switch winIdx
            case 1, winSize = [3 3];
            case 2, winSize = [5 5];
            case 3, winSize = [7 7];
        end
        state.Ifilt = noise_reduction(state.Ienh, winSize);

        % 3. Edge Detection
        edgeIdx = get(ddEdgeOp, 'Value');
        switch edgeIdx
            case 1, state.edges = edge_detection(state.Ifilt, 'canny');
            case 2, state.edges = edge_detection(state.Ifilt, 'sobel');
            case 3, state.edges = edge_detection(state.Ifilt, 'prewitt');
            case 4, state.edges = edge_detection(state.Ifilt, 'roberts');
        end

        % 4. Segmentation
        thresh.waterMax = round(get(sldWater, 'Value'));
        thresh.builtMin = round(get(sldBuilt, 'Value'));
        [state.BW_otsu, state.masks, state.composite] = segment_regions(state.Ifilt, state.Irgb, thresh);

        % 5. Channels
        [state.R, state.G, state.B] = channel_separation(state.Irgb);

        % 6. Spectral Indices
        state.indices = spectral_indices(state.Irgb);

        % 7. Metrics
        if ~isempty(state.cleanRef)
            m = evaluate_metrics(state.cleanRef, state.Ifilt);
        else
            m = evaluate_metrics(state.Igray, state.Ifilt);
        end
        state.metrics = m;

        % Update Metrics Panel
        set(txtMetrics, 'String', sprintf(...
            'MSE:  %7.3f\nRMSE: %7.3f\nPSNR: %6.2f dB\nSSIM: %7.4f', ...
            m.MSE, m.RMSE, m.PSNR, m.SSIM));
    end

    function onUpdateDisplay(~, ~)
        if state.imageLoaded
            updateDisplay();
        end
    end

    function updateDisplay()
        cla(axMain);
        modeVal = get(ddView, 'Value');

        switch modeVal
            case 1
                imshow(state.Irgb, 'Parent', axMain);
                title(axMain, '1. Original Satellite RGB Image', 'Color', 'w', 'FontSize', 12);

            case 2
                imshow(state.Igray, 'Parent', axMain);
                title(axMain, '2. Preprocessed Grayscale Representation', 'Color', 'w', 'FontSize', 12);

            case 3
                imshow(state.Ienh, 'Parent', axMain);
                title(axMain, sprintf('3. Contrast-Enhanced Image (CLAHE, ClipLimit=%.3f)', get(sldClip, 'Value')), ...
                    'Color', 'w', 'FontSize', 12);

            case 4
                imshow(state.Ifilt, 'Parent', axMain);
                title(axMain, '4. Denoised Image (2D Median Filtering)', 'Color', 'w', 'FontSize', 12);

            case 5
                imshow(state.edges, 'Parent', axMain);
                edgeNames = {'Canny', 'Sobel', 'Prewitt', 'Roberts'};
                title(axMain, sprintf('5. Boundary Edge Map (%s Operator)', edgeNames{get(ddEdgeOp, 'Value')}), ...
                    'Color', 'w', 'FontSize', 12);

            case 6
                imshow(state.BW_otsu, 'Parent', axMain);
                title(axMain, '6. Otsu Global Binary Segmentation (imbinarize)', 'Color', 'w', 'FontSize', 12);

            case 7
                % Multi-view: R, G, B Grayscale
                montageImg = cat(2, state.R, state.G, state.B);
                imshow(montageImg, 'Parent', axMain);
                title(axMain, '7. Colour-Channel Separation: Red (Left) | Green (Mid) | Blue (Right)', ...
                    'Color', 'w', 'FontSize', 12);

            case 8
                % Multi-view: Veg, Water, Built-up binary masks
                vegView   = uint8(state.masks.vegetation * 255);
                waterView = uint8(state.masks.water * 255);
                builtView = uint8(state.masks.builtup * 255);
                montageMasks = cat(2, vegView, waterView, builtView);
                imshow(montageMasks, 'Parent', axMain);
                title(axMain, '8. Region Maps: Vegetation (Left) | Water (Mid) | Built-Up (Right)', ...
                    'Color', 'w', 'FontSize', 12);

            case 9
                imshow(state.composite, 'Parent', axMain);
                title(axMain, '9. Colour-Coded Land-Cover Composite [Green=Veg, Blue=Water, Orange=Built-Up]', ...
                    'Color', 'w', 'FontSize', 12);

            case 10
                % Multispectral NDVI / NDWI
                ndviNorm = uint8((state.indices.NDVI + 1) * 127.5);
                ndwiNorm = uint8((state.indices.NDWI + 1) * 127.5);
                montageIndices = cat(2, ndviNorm, ndwiNorm);
                imshow(montageIndices, 'Parent', axMain);
                colormap(axMain, 'jet');
                title(axMain, '10. Spectral Indices: NDVI (Left) | NDWI (Right)', 'Color', 'w', 'FontSize', 12);
        end
    end

    function onExportResults(~, ~)
        if ~state.imageLoaded
            warndlg('Run pipeline on an image before exporting.', 'Notice');
            return;
        end

        outDir = fullfile(pwd, '..', 'outputs');
        if ~exist(outDir, 'dir'), mkdir(outDir); end

        imwrite(state.Irgb, fullfile(outDir, 'fig3_original.png'));
        imwrite(state.Igray, fullfile(outDir, 'grayscale.png'));
        imwrite(state.Ienh, fullfile(outDir, 'enhanced.png'));
        imwrite(state.Ifilt, fullfile(outDir, 'filtered.png'));
        imwrite(state.edges, fullfile(outDir, 'edges.png'));
        imwrite(state.BW_otsu, fullfile(outDir, 'binary.png'));
        imwrite(state.masks.vegetation, fullfile(outDir, 'mask_vegetation.png'));
        imwrite(state.masks.water, fullfile(outDir, 'mask_water.png'));
        imwrite(state.masks.builtup, fullfile(outDir, 'mask_builtup.png'));
        imwrite(state.composite, fullfile(outDir, 'composite_landcover.png'));
        imwrite(state.R, fullfile(outDir, 'channel_red.png'));
        imwrite(state.G, fullfile(outDir, 'channel_green.png'));
        imwrite(state.B, fullfile(outDir, 'channel_blue.png'));

        msgbox(sprintf('Successfully exported all 12 pipeline stages to:\n%s', outDir), 'Export Complete');
    end

    function name = getFileName(fullPath)
        [~, name, ext] = fileparts(fullPath);
        name = [name, ext];
    end
end

