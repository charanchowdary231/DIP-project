        'ForegroundColor', [1 1 1], ...
        'Units', 'normalized', 'Position', [0.55, 0.625, 0.40, 0.03]);

    % 5. Edge Detection Parameters
    uicontrol('Parent', pnlLeft, 'Style', 'text', ...
        'String', '--- Edge Detection Operator ---', ...
        'FontSize', 9, 'FontWeight', 'bold', ...
