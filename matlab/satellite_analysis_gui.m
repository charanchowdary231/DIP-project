        'ForegroundColor', [1 1 1], ...
        'Units', 'normalized', 'Position', [0.05, 0.535, 0.90, 0.03]);

    % 6. Segmentation Thresholds
    uicontrol('Parent', pnlLeft, 'Style', 'text', ...
        'String', '--- Region Segmentation Thresholds ---', ...
        'FontSize', 9, 'FontWeight', 'bold', ...
        'BackgroundColor', [0.16, 0.18, 0.23], ...
        'ForegroundColor', [0.4, 0.8, 1.0], ...
        'Units', 'normalized', 'Position', [0.05, 0.485, 0.90, 0.025]);

    lblWater = uicontrol('Parent', pnlLeft, 'Style', 'text', ...
        'String', 'Water Max Intensity: 75', ...
        'FontSize', 8, 'HorizontalAlignment', 'left', ...
