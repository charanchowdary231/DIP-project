        'Callback', @(s, e) set(lblClip, 'String', sprintf('Clip Limit: %.3f', get(s, 'Value'))));

    % 4. Denoising Parameters
    uicontrol('Parent', pnlLeft, 'Style', 'text', ...
        'String', '--- Noise Reduction (medfilt2) ---', ...
        'FontSize', 9, 'FontWeight', 'bold', ...
        'BackgroundColor', [0.16, 0.18, 0.23], ...
        'ForegroundColor', [0.4, 0.8, 1.0], ...
        'Units', 'normalized', 'Position', [0.05, 0.66, 0.90, 0.025]);

    uicontrol('Parent', pnlLeft, 'Style', 'text', ...
        'String', 'Median Window Size W:', ...
        'FontSize', 8, 'HorizontalAlignment', 'left', ...
        'BackgroundColor', [0.16, 0.18, 0.23], ...
        'ForegroundColor', [0.85, 0.85, 0.85], ...
        'Units', 'normalized', 'Position', [0.05, 0.63, 0.50, 0.022]);

    ddWindow = uicontrol('Parent', pnlLeft, 'Style', 'popupmenu', ...
        'String', {'[3 x 3] (Standard)', '[5 x 5] (Stronger)', '[7 x 7] (Heavy)'}, ...
