        'ForegroundColor', [0.85, 0.85, 0.85], ...
        'Units', 'normalized', 'Position', [0.05, 0.735, 0.90, 0.022]);

    sldClip = uicontrol('Parent', pnlLeft, 'Style', 'slider', ...
        'Min', 0.002, 'Max', 0.05, 'Value', 0.015, ...
