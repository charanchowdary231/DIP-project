        'Callback', @onUpdateDisplay);

    % 3. Contrast Enhancement Parameters
    uicontrol('Parent', pnlLeft, 'Style', 'text', ...
        'String', '--- Contrast Enhancement (CLAHE) ---', ...
        'FontSize', 9, 'FontWeight', 'bold', ...
        'BackgroundColor', [0.16, 0.18, 0.23], ...
        'ForegroundColor', [0.4, 0.8, 1.0], ...
        'Units', 'normalized', 'Position', [0.05, 0.77, 0.90, 0.025]);

    lblClip = uicontrol('Parent', pnlLeft, 'Style', 'text', ...
        'String', 'Clip Limit: 0.015', ...
        'FontSize', 8, 'HorizontalAlignment', 'left', ...
